import { StarMark } from "@/components/ui/StarMark";

/**
 * Фирменный знак в шапке раздела — крупный, тихий и дышащий.
 *
 * Стоит на страницах, которые вынесены в меню: у них шапка занимает
 * широкую полосу, справа от заголовка пусто, и знак заполняет её,
 * не мешая тексту. Он развёрнут и подрезан краем контейнера — тем же
 * приёмом, что подложки в кадрах товара и в карточках категорий.
 *
 * Пульс медленный, шесть секунд на цикл, и держится на прозрачности
 * с лёгким масштабом: композитору это ничего не стоит, а взгляд
 * замечает движение и понимает, что страница живая. При выключенном
 * движении в системе пульс гаснет — общее правило в `globals.css`.
 *
 * До `lg` знака нет: там шапка узкая, справа от заголовка места
 * не остаётся, и знак лёг бы прямо под текст.
 */
export function PageMark() {
  return (
    <span
      aria-hidden="true"
      className="pointer-events-none absolute -top-4 right-0 hidden lg:block"
    >
      <StarMark className="size-[clamp(11rem,17vw,17rem)] rotate-[-12deg] text-accent/[0.09] animate-mark" />
    </span>
  );
}
