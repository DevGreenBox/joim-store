import { StarMark } from "@/components/ui/StarMark";

/**
 * Фирменный знак в шапке раздела — крупный, тихий и дышащий.
 *
 * Стоит на страницах, которые вынесены в меню: у них шапка занимает
 * широкую полосу, справа от заголовка пусто, и знак заполняет её,
 * не мешая тексту. Целиком внутри колонки: за край он не выходит,
 * иначе читается обрезком, а не знаком.
 *
 * Пульс девять секунд на цикл, на прозрачности и почти незаметном
 * масштабе: композитору это ничего не стоит, а взгляд краем замечает,
 * что страница живая. При выключенном движении в системе пульс гаснет —
 * общее правило в `globals.css`.
 *
 * До `lg` знака нет: там шапка узкая, справа от заголовка места
 * не остаётся, и знак лёг бы прямо под текст.
 */
export function PageMark() {
  // Отступ справа — поле контейнера (48) плюс запас на поворот (21):
  // `right-0` отсчитывается от рамки блока, а не от колонки, и знак
  // вылезал за неё; повёрнутый квадрат к тому же шире собственной
  // стороны на 9% с каждого края.
  return (
    <span
      aria-hidden="true"
      className="pointer-events-none absolute top-6 right-[69px] hidden lg:block"
    >
      <StarMark className="size-[clamp(9rem,14vw,14rem)] rotate-[-12deg] text-accent/[0.18] animate-mark" />
    </span>
  );
}
